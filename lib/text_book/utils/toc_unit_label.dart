/// מחזירה תוית "כל ה..." מתאימה לפי המילה הראשונה בכותרת הפרק.
///
/// אם הכותרת מתחילה ב"פרק" → "כל הפרק", ב"דף" → "כל הדף" וכן הלאה.
/// לכל שאר הכותרות מוחזרת ברירת המחדל "כל הפיסקה".
String allUnitLabel(String chapterText) {
  final firstWord = chapterText.trim().split(RegExp(r'\s+')).firstOrNull ?? '';
  const labels = <String, String>{
    'פרק': 'כל הפרק',
    'דף': 'כל הדף',
    'פסוק': 'כל הפסוק',
    'סימן': 'כל הסימן',
    'אות': 'כל האות',
    'סעיף': 'כל הסעיף',
    'הלכה': 'כל ההלכה',
    'משנה': 'כל המשנה',
    'מאמר': 'כל המאמר',
    'שאלה': 'כל השאלה',
    'תשובה': 'כל התשובה',
    'עמוד': 'כל העמוד',
    'פרשה': 'כל הפרשה',
    'מזמור': 'כל המזמור',
  };
  return labels[firstWord] ?? 'כל הפיסקה';
}
