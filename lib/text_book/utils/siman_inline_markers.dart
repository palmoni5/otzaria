/// אותיות הפסקה (סימנים) בגוף הטקסט — מדרש רבה וחבריו.
///
/// במהדורות הדפוס כל פסקה נפתחת באות (א, ב, ג...) שמשמשת במראי מקומות.
/// בטקסט השמור במסד האותיות אינן קיימות — הן זמינות רק כמבנה alt-TOC
/// מסוג `Simanim` — ולכן הן מוזרקות כאן לתצוגה בלבד, בראש שורת הפסקה.
///
/// ההזרקה מוסיפה תוכן גלוי, ולכן חייבת לרוץ *אחרי* הזרקת סמני עוגן-מילה
/// ([injectLinkAnchorMarkers]) שמסתמכת על אופסטי התווים של הטקסט השמור.
library;

/// מקדים לשורה את אות הפסקה שלה, בסוגריים מרובעים ובהדגשה —
/// כמוסכמת `[אות ב]` המודפסת בתוספות רבי עקיבא איגר.
///
/// [label] היא האות מתוך ה-alt-TOC (`Simanim`), או `null` לשורה שאינה
/// פתיחת סימן — ואז השורה חוזרת כמות שהיא.
String prependSimanMarker(String html, String? label) {
  if (label == null || label.isEmpty || html.isEmpty) {
    return html;
  }
  return '<b>[$label]</b> $html';
}
